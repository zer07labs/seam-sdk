"""Voter proof-of-possession, `seam-voter-pop-v1` (seam-runtime #1687, runtime 0.87.0).

Asserts against `conformance/voter_pop_v1_payload_vector.json`, a byte-identical copy of the runtime's
fixture, generated by an implementation independent of the Rust one. The content digest, the frozen entry
bytes, the signed payload AND the deterministic Ed25519 signature are compared to its bytes. No bless mode.
"""

from __future__ import annotations

import json
from pathlib import Path

import pytest

from seam_sdk import (
    SeamClient,
    VoterPop,
    VoterPopTarget,
    sign_voter_pop,
    verify_voter_pop,
    vote_content_digest,
    vote_entry_bytes,
    voter_pop_payload,
)
from seam_sdk._gen.seam.api.v1 import seam_pb2 as pb
from seam_sdk.client import _vote_messages
from seam_sdk.crypto import VOTE_CONTENT_V1_DOMAIN, VOTER_POP_V1_DOMAIN

VECTOR = json.loads(
    (
        Path(__file__).resolve().parents[2]
        / "conformance"
        / "voter_pop_v1_payload_vector.json"
    ).read_text()
)
CASES = VECTOR["cases"]


def _target(c: dict) -> VoterPopTarget:
    t = c["target"]
    return VoterPopTarget(
        issuer=t["issuer"],
        tenant=t["tenant"],
        namespace=t["namespace"],
        session_id=t["session_id"],
        opened_at_millis=t["opened_at_millis"],
        audience=t["audience"],
    )


def _content(c: dict) -> bytes:
    k = c["content"]
    return vote_content_digest(
        k["mode"],
        k["proposal_id"],
        k["content"],
        k["participants"],
        k["on_behalf_of"],
        k["context"],
        features=[tuple(f) for f in k["features"]],
        policy=k["policy"],
    )


def test_vector_is_populated_and_domains_match() -> None:
    assert len(CASES) >= 11
    assert VOTER_POP_V1_DOMAIN.decode() == VECTOR["domain"]
    assert VOTE_CONTENT_V1_DOMAIN.decode() == VECTOR["content_domain"]


@pytest.mark.parametrize("case", CASES, ids=lambda c: c["name"])
def test_every_byte_matches_the_vector(case: dict) -> None:
    content = _content(case)
    assert content.hex() == case["content_digest_hex"]
    e = case["entry"]
    entry = vote_entry_bytes(
        e["kind"],
        e["participant"],
        e["proposal_id"],
        e["value"],
        e["reason"],
        confidence=e["confidence"],
        rationale_ref=e["rationale_ref"],
    )
    assert entry.hex() == case["entry_bytes_hex"]
    payload = voter_pop_payload(
        _target(case),
        case["voter_aid"],
        content,
        case["issued_at_ms"],
        case["expires_at_ms"],
        entry,
    )
    assert payload.hex() == case["payload_hex"]
    pop = sign_voter_pop(
        bytes.fromhex(case["seed_hex"]),
        _target(case),
        content,
        e,
        issued_at_ms=case["issued_at_ms"],
        expires_at_ms=case["expires_at_ms"],
    )
    assert pop.voter_aid == case["voter_aid"]
    assert pop.signature.hex() == case["signature_hex"]
    assert verify_voter_pop(
        _target(case),
        pop.voter_aid,
        content,
        pop.issued_at_ms,
        pop.expires_at_ms,
        entry,
        pop.signature,
    )


def test_the_other_cases_differ_from_basic() -> None:
    by = {c["name"]: c for c in CASES}
    for name in (
        "other-session",
        "other-opened-at",
        "other-audience",
        "other-content",
        "other-key",
    ):
        assert by[name]["signature_hex"] != by["basic"]["signature_hex"], name


def test_a_signature_does_not_verify_for_another_target() -> None:
    c = CASES[0]
    content = _content(c)
    pop = sign_voter_pop(
        bytes.fromhex(c["seed_hex"]),
        _target(c),
        content,
        c["entry"],
        issued_at_ms=c["issued_at_ms"],
        expires_at_ms=c["expires_at_ms"],
    )
    other = _target(c)._replace(session_id="s-other")
    assert not verify_voter_pop(
        other,
        pop.voter_aid,
        content,
        pop.issued_at_ms,
        pop.expires_at_ms,
        c["entry"],
        pop.signature,
    )


def test_minus_zero_confidence_folds_to_plus_zero() -> None:
    a = vote_entry_bytes("vote", "a", "p", "APPROVE", confidence=-0.0)
    b = vote_entry_bytes("vote", "a", "p", "APPROVE", confidence=0.0)
    assert a == b and a != vote_entry_bytes("vote", "a", "p", "APPROVE")


@pytest.mark.parametrize("window", [(10, 9), (0, 15 * 60 * 1000 + 1)])
def test_a_window_the_runtime_must_refuse_is_never_signed(window) -> None:
    c = CASES[0]
    with pytest.raises(ValueError, match="window"):
        sign_voter_pop(
            bytes.fromhex(c["seed_hex"]),
            _target(c),
            _content(c),
            c["entry"],
            issued_at_ms=window[0],
            expires_at_ms=window[1],
        )


def test_default_window_is_now_plus_five_minutes() -> None:
    c = CASES[0]
    pop = sign_voter_pop(
        bytes.fromhex(c["seed_hex"]), _target(c), _content(c), c["entry"]
    )
    assert pop.expires_at_ms - pop.issued_at_ms == 5 * 60 * 1000


def test_rest_and_proto_forms() -> None:
    pop = VoterPop("aid:pubkey:ed25519:x", 1, 2, b"\x01" * 64)
    assert "=" not in pop.to_rest()["pop"]["signature"]
    m = pop.to_pb(pb)
    assert m.pop.voter_aid == pop.voter_aid and m.pop.signature == pop.signature


# ── wiring: the proof reaches the wire ────────────────────────────────────────────────────────────


def _recording_client() -> tuple[SeamClient, dict]:
    seen: dict = {}
    client = object.__new__(SeamClient)

    def call(credential, rpc, aud, req, fn, timeout, retry):
        seen[rpc.rsplit("/", 1)[1]] = req
        return pb.SessionStep()

    client._credentialed_call = call  # type: ignore[method-assign]
    return client, seen


POP = VoterPop("aid:pubkey:ed25519:v", 1, 2, b"\x07" * 64)


def test_submit_vote_objection_ballot_carry_the_proof() -> None:
    client, seen = _recording_client()
    client.submit_vote("s", "risk", "p1", "APPROVE", proof=POP)
    client.submit_objection("s", "risk", "p1", "why", proof=POP.to_pb(pb))
    client.submit_ballot("s", "risk", "ar-1", pb.BALLOT_CHOICE_APPROVE, proof=POP)
    for rpc in ("SubmitVote", "SubmitObjection", "SubmitBallot"):
        assert (
            seen[rpc].HasField("proof")
            and seen[rpc].proof.pop.signature == POP.signature
        ), rpc
    client.submit_vote("s", "risk", "p1", "APPROVE")
    assert not seen["SubmitVote"].HasField("proof")


@pytest.mark.parametrize("bad", ["sig", {"pop": {}}, VoterPop("a", 1, 2, b"\x00" * 63)])
def test_a_malformed_proof_is_refused_before_the_wire(bad) -> None:
    client, seen = _recording_client()
    with pytest.raises((TypeError, ValueError)):
        client.submit_vote("s", "risk", "p1", "APPROVE", proof=bad)
    assert seen == {}


def test_run_decision_votes_carry_their_proofs() -> None:
    msgs = _vote_messages(
        [
            ("risk", "APPROVE", "", POP),
            ("fraud", "REJECT", "too risky"),
            pb.Vote(agent="x", value="ABSTAIN", proof=POP.to_pb(pb)),
        ]
    )
    assert msgs[0].proof.pop.voter_aid == POP.voter_aid and msgs[0].reason == ""
    assert not msgs[1].HasField("proof")
    assert msgs[2].HasField("proof")
    with pytest.raises(TypeError):
        _vote_messages([("a", "b", "c", POP, "extra")])


def test_features_are_framed_sorted_and_a_repeated_key_is_refused() -> None:
    by = {c["name"]: c for c in CASES}
    assert (
        by["features-order-a"]["content_digest_hex"]
        == by["features-order-b"]["content_digest_hex"]
    )
    base = ("macp.mode.decision.v1", "p1", "APPROVE", ["a"], [], [])
    assert vote_content_digest(
        *base, features={"b": "1", "a": "2"}
    ) == vote_content_digest(*base, features=[("a", "2"), ("b", "1")])
    with pytest.raises(ValueError, match="twice"):
        vote_content_digest(*base, features=[("a", "1"), ("a", "1")])


def test_the_policy_slot_accepts_the_served_ref_and_refuses_a_short_digest() -> None:
    base = ("macp.mode.quorum.v1", "ar-1", "x", ["a"], [], [])
    ref = pb.VotePolicyRef(policy_version="pol-1", rules_digest=b"\x05" * 32)
    assert vote_content_digest(*base, policy=ref) == vote_content_digest(
        *base, policy={"policy_version": "pol-1", "rules_digest_hex": "05" * 32}
    )
    assert vote_content_digest(*base, policy=ref) != vote_content_digest(*base)
    with pytest.raises(ValueError, match="32 bytes"):
        vote_content_digest(*base, policy=("pol-1", b"\x05" * 31))
