"""The Gate block v1 (`0x05`, `seam-gate-digest:v1`): every reader row of `gate_block_vector.json`.

Pinned against `conformance/gate_block_vector.json`, generated by the runtime's independent stdlib
generator and copied byte for byte (kept identical by its `sdk-digest-parity`). Framing: seam-runtime
`docs/specs/seam-gate-block.v1.md`.

Sections covered: `cases` (8), `presence_states` (3), `body_refusals` (36), `sequences` (13).

NOT covered, on purpose: `outage_classification` and `writer_refusals`. Both bind the WRITER (which
observed HTTP outcome may be sealed as `unavailable`, and with which reason); the body cannot see the
HTTP status, and the SDK is a reader that never writes a Gate block. They are skipped below, by name,
so the omission is visible in every run.

Refusal rows assert the REFUSAL only: rule names are advisory (§Refusal rules).
"""

from __future__ import annotations

import hashlib
import json
import struct
from pathlib import Path

import pytest

from seam_sdk import (
    CommitmentRefused,
    decode_commitment_trailers,
    decode_gate_body,
    gate_digest,
)

ROOT = Path(__file__).resolve().parents[2] / "conformance"
GATE = json.loads((ROOT / "gate_block_vector.json").read_text())
CASES = {c["name"]: c for c in GATE["cases"]}
DOC = hashlib.sha256(b"seam-governing-doc:test-vector").digest()
BE64_FIELDS = ("timeout_ms", "requested_at_ms", "given_up_at_ms")


def _governing_v2(env: str) -> bytes:
    body = b"\x02" + DOC + b"\x01" + struct.pack(">Q", len(env)) + env.encode()
    return b"\x06" + struct.pack("<I", len(body)) + body


def _as_vector_block(blk: dict) -> dict:
    """The decoder's Python shape in the vector's JSON shape (be64 as decimal strings, signature hex)."""
    out = dict(blk)
    for k in BE64_FIELDS:
        if k in out:
            out[k] = str(out[k])
    if "signature" in out:
        out["signature"] = out["signature"].hex()
    return out


def test_every_section_is_accounted_for():
    assert {k for k, v in GATE.items() if isinstance(v, list)} == {
        "cases",
        "presence_states",
        "body_refusals",
        "sequences",
        "outage_classification",
        "writer_refusals",
    }
    assert GATE["gate_digest_domain"] == "seam-gate-digest:v1"


@pytest.mark.parametrize("case", GATE["cases"], ids=lambda c: c["name"])
def test_case(case):
    body = bytes.fromhex(case["gate_body"])
    blk = decode_gate_body(body)
    assert _as_vector_block(blk) == case["block"]
    for k in BE64_FIELDS:
        if k in blk:
            assert isinstance(blk[k], int) and 0 <= blk[k] < 2**64
    assert gate_digest(body).hex() == case["gate_digest"]
    # The 27-byte prefix is all of F("seam-gate-digest:v1"); the body follows it whole.
    prefix = bytes.fromhex(case["gate_digest_preimage_prefix"])
    assert hashlib.sha256(prefix + body).hexdigest() == case["gate_digest"]
    assert (
        case["gate_digest_preimage_prefix"]
        == (struct.pack(">Q", 19) + b"seam-gate-digest:v1").hex()
    )
    assert (
        case["trailer"] == "05" + struct.pack("<I", len(body)).hex() + case["gate_body"]
    )
    assert case["field_10"] == "01" + struct.pack(">Q", 32).hex() + case["gate_digest"]
    # Beside its matching 0x06 body v2 the trailer frames field 10 the same way.
    got = decode_commitment_trailers(
        bytes.fromhex(case["trailer"]) + _governing_v2(blk["env"]), "v6"
    )
    assert got.field_10.hex() == case["field_10"]
    assert got.gate_block == blk


def test_the_max_be64_case_reads_full_64_bit_values():
    blk = decode_gate_body(bytes.fromhex(CASES["unavailable_max_be64"]["gate_body"]))
    assert (
        blk["timeout_ms"]
        == blk["requested_at_ms"]
        == blk["given_up_at_ms"]
        == 2**64 - 1
    )


@pytest.mark.parametrize("state", GATE["presence_states"], ids=lambda s: s["name"])
def test_presence_state(state):
    if state["trailer"] is None:
        assert (
            decode_commitment_trailers(_governing_v2("live"), "v6").field_10.hex()
            == (state["field_10"])
        )
        assert decode_commitment_trailers(b"", "v6").field_10.hex() == state["field_10"]
        return
    case = CASES[state["case"]]
    assert state["trailer"] == case["trailer"]
    trailer = bytes.fromhex(state["trailer"])
    env = decode_gate_body(trailer[5:])["env"]
    got = decode_commitment_trailers(trailer + _governing_v2(env), "v6")
    assert got.field_10.hex() == state["field_10"]


@pytest.mark.parametrize("row", GATE["body_refusals"], ids=lambda r: r["name"])
def test_body_refusal(row):
    assert row["expect"] == "refused"
    body = bytes.fromhex(row["gate_body"])
    with pytest.raises(CommitmentRefused):
        decode_gate_body(body)
    # Never hashed either.
    with pytest.raises(CommitmentRefused):
        gate_digest(body)


@pytest.mark.parametrize("row", GATE["sequences"], ids=lambda r: r["name"])
def test_sequence(row):
    assert row["scheme"] == "v6"
    if row["expect"] == "refused":
        with pytest.raises(CommitmentRefused):
            decode_commitment_trailers(row["trailers"], "v6")
        return
    got = decode_commitment_trailers(row["trailers"], "v6")
    assert got.field_10.hex() == row["expect"]["field_10"]
    assert got.field_11.hex() == row["expect"]["field_11"]
    assert got.field_12.hex() == row["expect"]["field_12"]


def test_a_gate_block_under_v5_refuses():
    t = bytes.fromhex(CASES["answered_automate_with_certificate"]["trailer"])
    with pytest.raises(CommitmentRefused):
        decode_commitment_trailers(t + _governing_v2("live"), "v5")


def test_a_legal_marker_outside_the_gate_and_governing_run_refuses():
    """The selection `0x04` (and `0x01`-`0x03`, `0x07`) are legal commitment trailers, but not part of
    the `0x05`/`0x06` input this reader takes: refused, never skipped."""
    for marker in (0x01, 0x02, 0x03, 0x04, 0x07):
        with pytest.raises(CommitmentRefused):
            decode_commitment_trailers(bytes([marker, 0, 0, 0, 0]), None)


