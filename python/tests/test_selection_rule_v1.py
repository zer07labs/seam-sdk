"""Option selection (`seam.selection.weighted_plurality` v1, runtime 0.90.0): body codec, field 9,
``decide()`` and the verifier's selection steps.

Pinned against ``conformance/selection_rule_v1_vectors.json``, copied verbatim from seam-runtime
``crates/seam-types/tests/fixtures/selection_rule_v1_vectors.json`` (generated by the runtime's
independent, stdlib-only ``scripts/selection_rule_v1_vectors.py``). The ``activation_cases``,
``policy_ingress_cases``, ``proposal_ingress_cases`` and ``flag_off_golden_cases`` groups pin the
runtime's open / ingress / commit gates, which run server-side only; a client never decides them, so
they are not exercised here. Signatures in ``sealed_cases`` are placeholders: the selection steps never
verify one (step 5's PoP re-check is pinned by ``voter_pop_v1_payload_vector.json``).
"""

from __future__ import annotations

import base64
import copy
import json
from pathlib import Path

import pytest

import seam_sdk.crypto as crypto
from seam_sdk import (
    SelectionDecodeError,
    aid_from_pubkey,
    decode_selection_body,
    explanation_digest,
    selection_body,
    selection_decide,
    selection_digest,
    verify_selection,
    verify_tct,
)
from seam_sdk._gen.seam.api.v1 import seam_pb2 as pb
from seam_sdk.client import commitment_view
from seam_sdk.crypto import _seam_commitment_digest
from seam_sdk.selection import decode_selection_trailer

ROOT = Path(__file__).resolve().parents[2] / "conformance"
V = json.loads((ROOT / "selection_rule_v1_vectors.json").read_text())
VERIFIED = next(c for c in V["sealed_cases"] if c["name"] == "verified")


def _entries(raw: list) -> list:
    """The vector's entries with their hex byte fields as bytes (the shape the digest takes)."""
    out = copy.deepcopy(raw)
    for e in out:
        vv = e.get("voter_verification")
        if vv is not None:
            for k in ("content_digest", "signature"):
                vv[k] = bytes.fromhex(vv[k])
            vv["signer_certificate"] = bytes.fromhex(vv.get("signer_certificate") or "")
    return out


# ── codec (§4.2-4.4) ─────────────────────────────────────────────────────────────────────────────────


def test_the_body_digest_field_9_and_trailer_match_the_codec_vector():
    codec = V["codec"]
    body = selection_body(codec["block"])
    assert body.hex() == codec["body"]
    assert selection_digest(body).hex() == codec["selection_digest"]
    assert crypto._selection_slot({"selection": body}).hex() == codec["field_9"]
    assert decode_selection_trailer(
        bytes.fromhex(codec["trailer"])
    ) == decode_selection_body(body)


def test_the_decoded_body_round_trips_to_the_block():
    codec = V["codec"]
    blk = decode_selection_body(bytes.fromhex(codec["body"]))
    assert blk["rules_digest"].hex() == codec["block"]["rules_digest"]
    assert selection_body(blk).hex() == codec["body"]


@pytest.mark.parametrize(
    "case", V["codec"]["trailer_refusals"], ids=lambda c: c["name"]
)
def test_every_trailer_refusal_is_refused_by_name(case):
    with pytest.raises(SelectionDecodeError) as e:
        decode_selection_trailer(bytes.fromhex(case["trailer"]))
    assert e.value.reason == case["reason"]


def test_a_block_the_runtime_could_not_have_sealed_is_never_hashed():
    blk = copy.deepcopy(V["codec"]["block"])
    blk["weights"] = [
        {"participant": "zed", "weight": 1},
        {"participant": "bob", "weight": 2},
    ]
    with pytest.raises(SelectionDecodeError, match="weights_not_canonical"):
        selection_body(blk)
    blk = copy.deepcopy(V["codec"]["block"])
    blk["winner_proposal_id"] = ""
    with pytest.raises(SelectionDecodeError, match="empty_winner"):
        selection_body(blk)
    blk = copy.deepcopy(V["codec"]["block"])
    blk["rules_digest"] = blk["rules_digest"].upper()
    with pytest.raises(ValueError, match="lowercase"):
        selection_body(blk)


# ── decide() (§3) ────────────────────────────────────────────────────────────────────────────────────


@pytest.mark.parametrize("case", V["rule_cases"], ids=lambda c: c["name"])
def test_every_rule_case(case):
    got = selection_decide(case["record"], case["entries"])
    want = case["expect"]
    assert got["result"] == want["result"]
    for k, v in want.items():
        assert got.get(k) == v, k


# ── the verifier's selection steps (§5 steps 6-9) ────────────────────────────────────────────────────


@pytest.mark.parametrize("case", V["sealed_cases"], ids=lambda c: c["name"])
def test_every_sealed_case(case):
    got = verify_selection(case["block"], case["entries"], case["action"])
    want = case["expect"]
    assert got.result == want["result"]
    if "at" in want:
        assert got.at == want["at"]
    if "recomputed" in want:
        assert got.recomputed == want["recomputed"]
    if want["result"] == "verified":
        assert got.ok
        assert got.winner_proposal_id == want["winner_proposal_id"]
        assert got.votes_linked == want["votes_linked"]
    else:
        assert not got.ok


# ── binding into the commitment digest (§4.4) ────────────────────────────────────────────────────────


@pytest.mark.parametrize(
    "case", V["commitment_digest_v5"]["cases"], ids=lambda c: c["name"]
)
def test_every_commitment_digest_case(case):
    c = dict(case["commitment"])
    c["explanation_digest"] = bytes.fromhex(case["explanation_digest"])
    c["selection_digest"] = case["selection_digest"]
    c["certificate_digest"] = case["certificate_digest"]
    c["governing_doc_sha256"] = case["governing_doc_sha256"]
    assert _seam_commitment_digest(c) == case["commitment_digest"]


def test_the_explanation_digest_carries_the_proposal_word():
    (case,) = [
        c
        for c in V["commitment_digest_v5"]["cases"]
        if c["name"] == "populated_selection_governed"
    ]
    assert (
        explanation_digest(_entries(VERIFIED["entries"])).hex()
        == case["explanation_digest"]
    )


def test_field_9_is_framed_from_the_block_and_a_disagreeing_digest_is_refused():
    (case,) = [
        c
        for c in V["commitment_digest_v5"]["cases"]
        if c["name"] == "populated_selection_governed"
    ]
    c = dict(case["commitment"])
    c["explanation"] = _entries(VERIFIED["entries"])
    c["governing_doc_sha256"] = case["governing_doc_sha256"]
    c["selection"] = VERIFIED["block"]
    assert _seam_commitment_digest(c) == case["commitment_digest"]
    c["selection"] = None
    (stripped,) = [
        x
        for x in V["commitment_digest_v5"]["cases"]
        if x["name"] == "populated_selection_stripped"
    ]
    assert _seam_commitment_digest(c) == stripped["commitment_digest"]
    c["selection"] = VERIFIED["block"]
    c["selection_digest"] = "00" * 32
    with pytest.raises(ValueError, match="does not match"):
        _seam_commitment_digest(c)


# ── end to end through verify_tct and commitment_view ────────────────────────────────────────────────

_SEED = bytes(range(32))


def _b64(b: bytes) -> str:
    return base64.urlsafe_b64encode(b).rstrip(b"=").decode()


def _issuer() -> str:
    from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey
    from cryptography.hazmat.primitives.serialization import Encoding, PublicFormat

    pub = Ed25519PrivateKey.from_private_bytes(_SEED).public_key()
    return aid_from_pubkey(pub.public_bytes(Encoding.Raw, PublicFormat.Raw))


def _tct(issuer: str, digest: str) -> str:
    """A seal-key TCT (seam-runtime #2031, S-4) certified by ``_SEED`` under ``issuer``."""
    from seal_key_tokens import mint

    return mint(
        _SEED,
        {"type": "seam:commitment", "commitment_digest": digest},
        issuer_aid=issuer,
    )


def _selection_commitment(block=None, action=None) -> dict:
    (case,) = [
        c
        for c in V["commitment_digest_v5"]["cases"]
        if c["name"] == "populated_selection_governed"
    ]
    c = dict(case["commitment"])
    c["explanation"] = _entries(VERIFIED["entries"])
    c["governing_doc_sha256"] = case["governing_doc_sha256"]
    c["selection"] = block if block is not None else VERIFIED["block"]
    if action is not None:
        c["action"] = action
    return c


@pytest.fixture
def no_pop(monkeypatch):
    # The vector's voter signatures are placeholders, so step 5 (the PoP re-check, pinned elsewhere) is
    # stubbed; every other step — the TCT, field 9, steps 6-9 — runs for real.
    monkeypatch.setattr(crypto, "verify_commitment_voters", lambda *a, **k: True)


def test_a_selection_commitment_verifies_end_to_end(no_pop):
    issuer = _issuer()
    c = _selection_commitment()
    assert (
        verify_tct(issuer, _tct(issuer, _seam_commitment_digest(c)), c, now_s=0) is True
    )


def test_a_losing_action_under_a_valid_tct_fails_the_winner_recompute(no_pop):
    """The TCT binds what was sealed; the recompute catches a seal whose action is not the winner."""
    issuer = _issuer()
    c = _selection_commitment(action="rate 5%")
    assert (
        verify_tct(issuer, _tct(issuer, _seam_commitment_digest(c)), c, now_s=0)
        is False
    )


def test_a_stripped_or_edited_block_fails_the_tct(no_pop):
    issuer = _issuer()
    c = _selection_commitment()
    jws = _tct(issuer, _seam_commitment_digest(c))
    stripped = dict(c, selection=None)
    assert verify_tct(issuer, jws, stripped, now_s=0) is False
    edited = copy.deepcopy(VERIFIED["block"])
    edited["weights"][0]["weight"] = 3
    assert verify_tct(issuer, jws, dict(c, selection=edited), now_s=0) is False


def test_a_block_without_entries_fails_closed(no_pop):
    issuer = _issuer()
    c = _selection_commitment()
    jws = _tct(issuer, _seam_commitment_digest(c))
    c.pop("explanation")
    c["explanation_digest"] = explanation_digest(_entries(VERIFIED["entries"]))
    assert verify_tct(issuer, jws, c, now_s=0) is False


def test_a_malformed_body_fails_closed_and_never_reads_as_absent(no_pop):
    issuer = _issuer()
    c = _selection_commitment()
    jws = _tct(issuer, _seam_commitment_digest(c))
    body = selection_body(VERIFIED["block"]) + b"\x00"
    assert verify_tct(issuer, jws, dict(c, selection=body), now_s=0) is False


def test_commitment_view_carries_the_selection_with_explicit_presence():
    blk = VERIFIED["block"]
    rec = pb.SelectionRecord(
        rule=blk["rule"],
        rule_version=blk["rule_version"],
        default_weight=blk["default_weight"],
        weights=[pb.SelectionWeight(**w) for w in blk["weights"]],
        tie=blk["tie"],
        abstention=blk["abstention"],
        min_ballots=blk["min_ballots"],
        policy_version=blk["policy_version"],
        rules_digest=bytes.fromhex(blk["rules_digest"]),
        participants=blk["participants"],
        on_behalf_of=blk["on_behalf_of"],
        context=[pb.SelectionContext(**x) for x in blk["context"]],
        winner_proposal_id=blk["winner_proposal_id"],
    )
    served = pb.Commitment(id="cmt:x", action="rate 7%", selection=rec)
    view = commitment_view(served)
    assert selection_body(view["selection"]).hex() == selection_body(blk).hex()
    assert commitment_view(pb.Commitment(id="cmt:x"))["selection"] is None
    proposal = pb.Commitment(
        explanation=[
            pb.ExplanationEntry(kind=pb.EXPLANATION_KIND_PROPOSAL, proposal_id="p1")
        ]
    )
    assert commitment_view(proposal)["explanation"][0]["kind"] == "proposal"
