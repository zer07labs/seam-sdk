// JCS + toolInputDigest must reproduce the runtime's cross-language vector byte-for-byte — and
// therefore match the Python SDK character-for-character. The vector is COPIED from the runtime
// (`crates/seam-api/tests/fixtures/`), never re-derived; a mismatch is a contract break.

import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { test } from "node:test";


import { jcsCanonicalize, toolInputDigest } from "../src/crypto.js";

const VECTOR = JSON.parse(
  readFileSync(
    join(dirname(fileURLToPath(import.meta.url)), "..", "..", "conformance", "authorize_jcs_digest_vector.json"),
    "utf8",
  ),
) as { cases: { name: string; input: unknown; canonical: string; digest: string }[] };

const INT_VECTOR = JSON.parse(
  readFileSync(
    join(dirname(fileURLToPath(import.meta.url)), "..", "..", "conformance", "authorize_jcs_int_extended.json"),
    "utf8",
  ),
) as { cases: { name: string; why: string; int: string; canonical?: string; digest?: string; rejected?: boolean }[] };

const dec = new TextDecoder();

test("every runtime vector case is byte-exact", () => {
  for (const c of VECTOR.cases) {
    const canonical = jcsCanonicalize(c.input);
    assert.equal(dec.decode(canonical), c.canonical, c.name);
    assert.equal(toolInputDigest(canonical), c.digest, c.name);
  }
});

test("ES6 number rendering edges (ECMA-262 Number::toString)", () => {
  const cases: [number, string][] = [
    [1e-7, "1e-7"],
    [0.000001, "0.000001"],
    [1.5e22, "1.5e+22"],
    [100.0, "100"],
    [-0, "0"],
  ];
  for (const [v, want] of cases) assert.equal(dec.decode(jcsCanonicalize(v)), want);
});

test("unrepresentable inputs are rejected", () => {
  assert.throws(() => jcsCanonicalize(NaN));
  assert.throws(() => jcsCanonicalize(Infinity));
  assert.throws(() => jcsCanonicalize(2n ** 53n + 1n));
  assert.throws(() => jcsCanonicalize(() => {}));
});

test("lone surrogates are rejected (parity with Python/Rust)", () => {
  assert.throws(() => jcsCanonicalize({ s: "\ud800" }));
  assert.throws(() => jcsCanonicalize("\udfff"));
  // A well-formed surrogate PAIR is fine (it's just a supplementary-plane char).
  assert.equal(new TextDecoder().decode(jcsCanonicalize("😀")), '"😀"');
});

// The SDK-owned integer cases. Unlike the runtime vector above, this file is emitted by the PYTHON
// SDK — which is exactly what makes it useful here: `jcsBigInt` is a separate implementation of the
// same rule, so reproducing these bytes proves the two languages agree rather than that each is
// self-consistent. `int` is parsed with BigInt, never as a JSON number, because JSON.parse would
// have already lost the precision under test.
test("every SDK integer vector case matches Python byte-for-byte", () => {
  let accepted = 0;
  let refused = 0;
  for (const c of INT_VECTOR.cases) {
    const v = BigInt(c.int);
    if (c.rejected) {
      refused++;
      assert.throws(() => jcsCanonicalize(v), `${c.name} must be refused: ${c.why}`);
      continue;
    }
    accepted++;
    const canonical = jcsCanonicalize(v);
    assert.equal(dec.decode(canonical), c.canonical, c.name);
    assert.equal(toolInputDigest(canonical), c.digest, c.name);
  }
  // Guard-the-guard: a loop over an empty or one-sided case list would pass while proving nothing,
  // and this vector is regenerated by a script that could silently emit either.
  assert.ok(accepted >= 8 && refused >= 8, `vector is one-sided: ${accepted} accepted, ${refused} refused`);
});

test("a bigint and the number with the same value canonicalize identically", () => {
  // The Python-side asymmetry that started seam-sdk#60 was the int arm refusing what the float arm
  // accepted. TypeScript's arms are bigint and number; they must answer the same question.
  for (const [big, num] of [
    [10000000000000000n, 1e16],
    [100000000000000000000n, 1e20],
    [9007199254740994n, 9007199254740994],
  ] as [bigint, number][]) {
    assert.equal(dec.decode(jcsCanonicalize(big)), dec.decode(jcsCanonicalize(num)));
  }
});
